// Star is the only filled glyph (stroke icons would read as hollow at 12px).
const FILLED = new Set(['star']);
const STAR_PATH = '<polygon points="12 2 15.09 8.26 22 9.27 17 14.14 18.18 21.02 12 17.77 5.82 21.02 7 14.14 2 9.27 8.91 8.26 12 2"/>';

export function icon(name, size = 14) {
  if (name === 'star') {
    return `<svg class="svg-icon svg-star" width="${size}" height="${size}" viewBox="0 0 24 24" fill="currentColor" stroke="none" aria-hidden="true">${STAR_PATH}</svg>`;
  }
  const body = PATHS[name] || PATHS.file;
  const cls = name === 'spinner' ? `svg-icon svg-spinner spinning-svg` : `svg-icon svg-${name}`;
  return `<svg class="${cls}" width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${body}</svg>`;
}

export function fileKindIcon(name, isDirectory, size = 14) {
  if (isDirectory) return icon('folder', size);
  const ext = (name.split('.').pop() || '').toLowerCase();
  if (['png', 'jpg', 'jpeg', 'gif', 'webp', 'ico', 'svg', 'bmp', 'avif'].includes(ext)) return icon('image', size);
  if (name === '.env' || ext === 'env' || name === '.gitignore' || ext === 'lock' || name.endsWith('-lock.json')) return icon('lock', size);
  return icon('file', size);
}

